#!/usr/bin/env python3
"""
Engine Bola — Telegram Premium Channel Publisher (MTProto / Telethon)

Publishes the rich HTML report generated by scripts/auto_bot.mjs (with all
<tg-emoji emoji-id="..."> club crests & league logos) directly to Broadcast
Channels (e.g. @enginebola) using the Owner's Telegram Premium StringSession.

Why:
  Telegram Bot API 9.4 renders <tg-emoji> in DMs & Supergroups, but strips
  bot-sent <tg-emoji> in Broadcast Channels. Publishing via a Telegram Premium
  Channel Admin posts cleanly AS the channel ("Engine Bola") with FULL club
  crests — and Telegram automatically forwards that exact full-crest post into
  the linked Discussion Group ("Engine Bola Diskusi").
"""

from __future__ import annotations

import asyncio
import json
import os
import sys
from html.parser import HTMLParser
from pathlib import Path
from typing import Any


def utf16_len(s: str) -> int:
    """Telegram MTProto entity offsets & lengths are measured in UTF-16 code units."""
    return len(s.encode("utf-16-le")) // 2


class TelegramHtmlEntityParser(HTMLParser):
    """Converts Telegram Bot API HTML (including <tg-emoji> & <blockquote>) into plain text + entity descriptors."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.parts: list[str] = []
        self.utf16_pos: int = 0
        self.stack: list[dict[str, Any]] = []
        self.entities: list[dict[str, Any]] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        t = tag.lower()
        attr_map = {k.lower(): (v or "") for k, v in attrs}
        if t == "br":
            self.parts.append("\n")
            self.utf16_pos += 1
            return
        if t in ("b", "strong", "i", "em", "code", "blockquote", "a", "tg-emoji", "u", "s", "del"):
            self.stack.append({
                "tag": t,
                "offset": self.utf16_pos,
                "attrs": attr_map,
            })

    def handle_data(self, data: str) -> None:
        if not data:
            return
        self.parts.append(data)
        self.utf16_pos += utf16_len(data)

    def handle_endtag(self, tag: str) -> None:
        t = tag.lower()
        for i in range(len(self.stack) - 1, -1, -1):
            if self.stack[i]["tag"] == t:
                item = self.stack.pop(i)
                length = self.utf16_pos - item["offset"]
                if length > 0:
                    self.entities.append({
                        "tag": t,
                        "offset": item["offset"],
                        "length": length,
                        "attrs": item["attrs"],
                    })
                break

    def result(self) -> tuple[str, list[dict[str, Any]]]:
        # Sort by offset ascending, outer spans before inner spans
        ents = sorted(self.entities, key=lambda e: (e["offset"], -e["length"]))
        return "".join(self.parts), ents


def parse_telegram_html(html_text: str) -> tuple[str, list[dict[str, Any]]]:
    parser = TelegramHtmlEntityParser()
    parser.feed(html_text)
    parser.close()
    return parser.result()


def build_telethon_entities(raw_entities: list[dict[str, Any]]) -> list[Any]:
    from telethon.tl.types import (
        MessageEntityBlockquote,
        MessageEntityBold,
        MessageEntityCode,
        MessageEntityCustomEmoji,
        MessageEntityItalic,
        MessageEntityStrike,
        MessageEntityTextUrl,
        MessageEntityUnderline,
    )

    out = []
    for e in raw_entities:
        tag = e["tag"]
        offset = int(e["offset"])
        length = int(e["length"])
        attrs = e["attrs"]
        if tag in ("b", "strong"):
            out.append(MessageEntityBold(offset=offset, length=length))
        elif tag in ("i", "em"):
            out.append(MessageEntityItalic(offset=offset, length=length))
        elif tag == "code":
            out.append(MessageEntityCode(offset=offset, length=length))
        elif tag == "blockquote":
            out.append(MessageEntityBlockquote(offset=offset, length=length))
        elif tag == "u":
            out.append(MessageEntityUnderline(offset=offset, length=length))
        elif tag in ("s", "del"):
            out.append(MessageEntityStrike(offset=offset, length=length))
        elif tag == "a":
            url = attrs.get("href", "").strip()
            if url:
                out.append(MessageEntityTextUrl(offset=offset, length=length, url=url))
        elif tag == "tg-emoji":
            eid = attrs.get("emoji-id", "").strip()
            if eid.isdigit():
                out.append(MessageEntityCustomEmoji(offset=offset, length=length, document_id=int(eid)))
    return out


def chunk_html_for_telegram(html_text: str, max_utf16: int = 3900) -> list[str]:
    plain, _ = parse_telegram_html(html_text)
    if utf16_len(plain) <= max_utf16:
        return [html_text]
    chunks: list[str] = []
    cur = ""
    for block in html_text.split("\n\n"):
        cand = f"{cur}\n\n{block}" if cur else block
        cand_plain, _ = parse_telegram_html(cand)
        if utf16_len(cand_plain) > max_utf16 and cur:
            chunks.append(cur)
            cur = block
        else:
            cur = cand
    if cur:
        chunks.append(cur)
    return chunks


async def publish_pending(payload_path: Path) -> None:
    if not payload_path.exists():
        print("[PremiumPublisher] No pending channel post found — nothing to publish.")
        return

    api_id_raw = os.environ.get("TG_API_ID", "").strip()
    api_hash = os.environ.get("TG_API_HASH", "").strip()
    session_str = os.environ.get("TG_SESSION_STRING", "").strip()

    if not (api_id_raw.isdigit() and api_hash and session_str):
        print("[PremiumPublisher] TG_API_ID / TG_API_HASH / TG_SESSION_STRING not configured — skipping.")
        return

    data = json.loads(payload_path.read_text(encoding="utf-8"))
    targets = [str(t).strip() for t in (data.get("targets") or []) if str(t).strip()]
    html_body = str(data.get("html") or "").strip()
    dashboard_url = str(data.get("dashboard_url") or "https://enginebola.web.id").strip()

    if not targets or not html_body:
        print("[PremiumPublisher] Empty targets or HTML body — skipping.")
        return

    footer = f'\n\n🔗 <a href="{dashboard_url}"><b>Buka VIP Dashboard · Engine Bola</b></a>'
    full_html = html_body + footer
    chunks = chunk_html_for_telegram(full_html)

    from telethon import TelegramClient
    from telethon.sessions import StringSession

    client = TelegramClient(StringSession(session_str), int(api_id_raw), api_hash)
    await client.connect()
    try:
        if not await client.is_user_authorized():
            raise RuntimeError("TG_SESSION_STRING is invalid or expired. Regenerate it with scripts/gen_tg_session.py.")
        me = await client.get_me()
        is_prem = bool(getattr(me, "premium", False))
        print(f"[PremiumPublisher] Connected as id={getattr(me, 'id', '?')} | telegram_premium={is_prem}")
        if not is_prem:
            print("[PremiumPublisher] WARNING: Account does not show active Telegram Premium — custom emojis may fall back to standard emoji.")

        for target in targets:
            peer: Any = int(target) if target.lstrip("-").isdigit() else target
            entity = await client.get_input_entity(peer)
            for idx, html_chunk in enumerate(chunks):
                text, raw_ents = parse_telegram_html(html_chunk)
                tl_ents = build_telethon_entities(raw_ents)
                custom_cnt = sum(1 for e in raw_ents if e["tag"] == "tg-emoji")
                sent = await client.send_message(
                    entity,
                    text,
                    formatting_entities=tl_ents,
                    link_preview=False,
                )
                print(
                    f"[PremiumPublisher] Published chunk {idx + 1}/{len(chunks)} to {target} "
                    f"(msg_id={sent.id}, utf16_len={utf16_len(text)}, custom_emojis={custom_cnt})"
                )
                if idx < len(chunks) - 1:
                    await asyncio.sleep(1.5)
    finally:
        await client.disconnect()

    try:
        payload_path.unlink()
    except OSError:
        pass


def main() -> None:
    if "--self-test" in sys.argv:
        sample = (
            '<tg-emoji emoji-id="520001">⚽</tg-emoji> <b>ENGINE BOLA</b>\n'
            '<blockquote>1. <tg-emoji emoji-id="520002">🏴󠁧󠁢󠁥󠁮󠁧󠁿</tg-emoji> Crystal Palace vs '
            '<tg-emoji emoji-id="520003">🇪🇸</tg-emoji> Real Sociedad\n'
            '<i>Europa League</i> · <code>1.85</code></blockquote>\n'
            '<a href="https://enginebola.web.id"><b>Buka VIP Dashboard</b></a>'
        )
        text, ents = parse_telegram_html(sample)
        u16 = text.encode("utf-16-le")
        for e in ents:
            slice_txt = u16[e["offset"] * 2 : (e["offset"] + e["length"]) * 2].decode("utf-16-le")
            assert slice_txt, f"Empty entity slice for {e}"
            if e["tag"] == "tg-emoji":
                assert slice_txt in ("⚽", "🏴󠁧󠁢󠁥󠁮󠁧󠁿", "🇪🇸"), f"Bad custom emoji slice: {slice_txt!r}"
        print(f"[SelfTest OK] text_len={len(text)} utf16={utf16_len(text)} entities={len(ents)}")
        return

    repo_root = Path(__file__).resolve().parent.parent
    payload_path = repo_root / "data" / "pending_channel_post.json"
    asyncio.run(publish_pending(payload_path))


if __name__ == "__main__":
    main()
