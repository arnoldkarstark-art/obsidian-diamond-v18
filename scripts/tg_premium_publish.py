"""
Engine Bola — Telegram Premium Channel Publisher (MTProto / Telethon)
with Automatic Owner-Override Lock & Session-Logout Bot API Failsafe.

Publishes the rich HTML report generated by scripts/auto_bot.mjs (with all
<tg-emoji emoji-id="..."> club crests & league logos) directly to Broadcast
Channels (e.g. @enginebola) using the Owner's Telegram Premium StringSession.

Built-in 3-Layer Failsafe (ZERO missed channel broadcasts):
  1. Owner-Override Lock:
     Verifies the connected Telethon account ID matches the LIVE `owner_id`
     from Cloudflare KV (`expected_owner_id`). If Emergency Owner Takeover
     (`/auth <RECOVERY_PIN>`) switched ownership to a new Telegram account,
     the old session is IMMEDIATELY BLOCKED from posting.
  2. Logged-Out / Revoked / Expired / Error Auto-Fallback:
     If someone terminates the `enginebola` session, Telegram Premium expires,
     Telethon fails to install, or MTProto raises any error, every unpublished
     channel automatically receives the crisp Unicode-flag report via standard
     Telegram Bot API (zero external Python deps — uses stdlib urllib).
  3. Instant Owner DM Alert:
     Whenever the failsafe triggers, the bot sends a concise DM alert to the
     current `expected_owner_id` explaining the exact reason and recovery step.
"""

