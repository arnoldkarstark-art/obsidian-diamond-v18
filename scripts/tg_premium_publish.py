def utf16_len(s: str) -> int:
    """Telegram MTProto entity offsets & lengths are measured in UTF-16 code units."""
    return len(s.encode("utf-16-le")) // 2


def strip_tg_emoji_tags(html_text: str) -> str:
    return re.sub(r'<tg-emoji\s+emoji-id="[^"]+">([\s\S]*?)</tg-emoji>', r"\1", str(html_text or ""))


class TelegramHtmlEntityParser(HTMLParser):
    """Converts Telegram Bot API HTML (including <tg-emoji> & <blockquote>) into plain text + entity descriptors."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.parts: list[str] = []
        self.utf16_pos: int = 0
        self.stack: list[dict[str, Any]] = []
        self.entities: list[dict[str, Any]] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        t = tag.lower()
        attr_map = {k.lower(): (v or "") for k, v in attrs}
        if t == "br":
            self.parts.append("\n")
            self.utf16_pos += 1
            return
        if t in ("b", "strong", "i", "em", "code", "blockquote", "a", "tg-emoji", "u", "s", "del"):
            self.stack.append({
                "tag": t,
                "offset": self.utf16_pos,
                "attrs": attr_map,
            })

    def handle_data(self, data: str) -> None:
        if not data:
            return
        self.parts.append(data)
        self.utf16_pos += utf16_len(data)

    def handle_endtag(self, tag: str) -> None:
        t = tag.lower()
        for i in range(len(self.stack) - 1, -1, -1):
            if self.stack[i]["tag"] == t:
                item = self.stack.pop(i)
                length = self.utf16_pos - item["offset"]
                if length > 0:
                    self.entities.append({
                        "tag": t,
                        "offset": item["offset"],
                        "length": length,
                        "attrs": item["attrs"],
                    })
                break

    def result(self) -> tuple[str, list[dict[str, Any]]]:
        ents = sorted(self.entities, key=lambda e: (e["offset"], -e["length"]))
        return "".join(self.parts), ents


def parse_telegram_html(html_text: str) -> tuple[str, list[dict[str, Any]]]:
    parser = TelegramHtmlEntityParser()
    parser.feed(html_text)
    parser.close()
    return parser.result()


def build_telethon_entities(raw_entities: list[dict[str, Any]]) -> list[Any]:
    from telethon.tl.types import (
        MessageEntityBlockquote,
        MessageEntityBold,
        MessageEntityCode,
        MessageEntityCustomEmoji,
        MessageEntityItalic,
        MessageEntityStrike,
        MessageEntityTextUrl,
        MessageEntityUnderline,
    )

    out = []
    for e in raw_entities:
        tag = e["tag"]
        offset = int(e["offset"])
        length = int(e["length"])
        attrs = e["attrs"]
        if tag in ("b", "strong"):
            out.append(MessageEntityBold(offset=offset, length=length))
        elif tag in ("i", "em"):
            out.append(MessageEntityItalic(offset=offset, length=length))
        elif tag == "code":
            out.append(MessageEntityCode(offset=offset, length=length))
        elif tag == "blockquote":
            out.append(MessageEntityBlockquote(offset=offset, length=length))
        elif tag == "u":
            out.append(MessageEntityUnderline(offset=offset, length=length))
        elif tag in ("s", "del"):
            out.append(MessageEntityStrike(offset=offset, length=length))
        elif tag == "a":
            url = attrs.get("href", "").strip()
            if url:
                out.append(MessageEntityTextUrl(offset=offset, length=length, url=url))
        elif tag == "tg-emoji":
            eid = attrs.get("emoji-id", "").strip()
            if eid.isdigit():
                out.append(MessageEntityCustomEmoji(offset=offset, length=length, document_id=int(eid)))
    return out


def chunk_html_for_telegram(html_text: str, max_utf16: int = 3850) -> list[str]:
    plain, _ = parse_telegram_html(html_text)
    if utf16_len(plain) <= max_utf16:
        return [html_text]
    chunks: list[str] = []
    cur = ""
    for block in html_text.split("\n\n"):
        cand = f"{cur}\n\n{block}" if cur else block
        cand_plain, _ = parse_telegram_html(cand)
        if utf16_len(cand_plain) > max_utf16 and cur:
            chunks.append(cur)
            cur = block
        else:
            cur = cand
    if cur:
        chunks.append(cur)
    return chunks


# ---- Zero-Dependency Bot API Failsafe (urllib stdlib only) ----
def bot_api_send_message(
    bot_token: str,
    chat_id: str,
    html_text: str,
    dashboard_url: str | None = None,
) -> tuple[bool, str]:
    clean_token = str(bot_token or "").strip().strip('"').strip("'")
    if not clean_token:
        return False, "TELEGRAM_BOT_TOKEN not set"

    url = f"https://api.telegram.org/bot{clean_token}/sendMessage"
    chunks = chunk_html_for_telegram(html_text, max_utf16=3800)

    for idx, chunk in enumerate(chunks):
        sent = False
        last_err = "unknown"
        strip_custom = False
        for attempt in range(1, 4):
            use_btn = bool(dashboard_url) and (attempt == 1 or strip_custom) and idx == len(chunks) - 1
            base_chunk = strip_tg_emoji_tags(chunk) if strip_custom else chunk
            text_out = (
                f"{base_chunk}\n\n🔗 {dashboard_url}"
                if (dashboard_url and not use_btn and idx == len(chunks) - 1)
                else base_chunk
            )
            payload: dict[str, Any] = {
                "chat_id": chat_id,
                "text": text_out,
                "parse_mode": "HTML",
                "disable_web_page_preview": True,
            }
            if use_btn:
                payload["reply_markup"] = {
                    "inline_keyboard": [[{"text": "Buka VIP Dashboard · Engine Bola", "url": dashboard_url}]]
                }

            req = urllib.request.Request(
                url,
                data=json.dumps(payload).encode("utf-8"),
                headers={"Content-Type": "application/json"},
                method="POST",
            )
            status = 0
            resp_json: dict[str, Any] = {}
            try:
                with urllib.request.urlopen(req, timeout=20) as resp:
                    status = resp.status
                    resp_json = json.loads(resp.read().decode("utf-8", errors="replace"))
            except urllib.error.HTTPError as he:
                status = he.code
                try:
                    resp_json = json.loads(he.read().decode("utf-8", errors="replace"))
                except Exception:
                    resp_json = {"description": str(he)}
            except Exception as e:
                last_err = str(e)
                time.sleep(2)
                continue

            if status == 200 and resp_json.get("ok"):
                sent = True
                break
            if status == 400 and not strip_custom and "<tg-emoji" in chunk:
                strip_custom = True
                continue
            if status == 429 and attempt < 3:
                retry_after = int((resp_json.get("parameters") or {}).get("retry_after") or 15)
                time.sleep(min(60, max(5, retry_after + 3)))
                continue
            last_err = f"HTTP {status}: {resp_json.get('description') or resp_json}"
            break

        if not sent:
            return False, last_err
        if idx < len(chunks) - 1:
            time.sleep(1.2)
    return True, "ok"


def execute_bot_api_failsafe(
    remaining_targets: list[str],
    fallback_html: str,
    dashboard_url: str,
    expected_owner_id: str | None,
    reason_code: str,
    reason_detail: str,
) -> bool:
    """Delivers unpublished channel posts via Bot API and alerts the live Owner via DM."""
    bot_token = os.environ.get("TELEGRAM_BOT_TOKEN", "").strip()
    print(f"::warning title=Premium Publisher Failsafe ({reason_code})::{reason_detail}")
    print(f"[Failsafe] Activating Bot API fallback ({reason_code}): {reason_detail}")

    if not bot_token:
        print("[Failsafe] ERROR: TELEGRAM_BOT_TOKEN missing — cannot run Bot API fallback.")
        return False

    all_ok = True
    delivered_targets: list[str] = []
    for target in remaining_targets:
        ok, err = bot_api_send_message(bot_token, target, fallback_html, dashboard_url=dashboard_url)
        if ok:
            delivered_targets.append(target)
            print(f"[Failsafe] Delivered Unicode-flag report to {target} via Bot API (zero downtime).")
        else:
            all_ok = False
            print(f"[Failsafe] FAILED Bot API fallback for {target}: {err}")

    if expected_owner_id:
        title_map = {
            "OWNER_OVERRIDE_MISMATCH": "OWNER OVERRIDE DETECTED · SESI LAMA DIBLOKIR",
            "SESSION_LOGGED_OUT": "SESI TELEGRAM PREMIUM TER-LOGOUT / REVOKED",
            "PREMIUM_EXPIRED": "TELEGRAM PREMIUM TIDAK AKTIF",
            "TELETHON_UNAVAILABLE": "LIBRARY TELETHON GAGAL DIMUAT",
            "MTPROTO_ERROR": "GANGGUAN PUBLISH MTPROTO",
        }
        headline = title_map.get(reason_code, "FAILSAFE CHANNEL AKTIF")
        targets_txt = ", ".join(delivered_targets) if delivered_targets else "(gagal kirim)"
        alert_html = "\n".join([
            f"⚠️ <b>ENGINE BOLA · {html_escape(headline)}</b>",
            "",
            f"<blockquote><b>Status:</b> Laporan tetap terkirim otomatis ke <b>{html_escape(targets_txt)}</b> menggunakan Bot API (bendera Unicode) agar channel tidak kosong.",
            f"<b>Penyebab:</b> {html_escape(reason_detail)}</blockquote>",
            "",
            "<b>Cara Pulihkan Logo Klub Asli di Channel:</b>",
            "1. Jalankan ulang <code>python gen_tg_session.py</code> dengan akun Owner Telegram Premium aktif.",
            "2. Update GitHub Secret <code>TG_SESSION_STRING</code> (dan <code>TG_API_ID</code> / <code>TG_API_HASH</code> jika ganti akun).",
            "<i>Jika baru melakukan Emergency Owner Takeover (/auth RECOVERY_PIN), sesi akun lama sudah otomatis diblokir oleh Owner-Lock.</i>",
        ])
        dm_ok, dm_err = bot_api_send_message(bot_token, str(expected_owner_id), alert_html, dashboard_url=None)
        print(f"[Failsafe] Owner DM alert -> ok={dm_ok}" + ("" if dm_ok else f" err={dm_err}"))

    return all_ok


def classify_mtproto_error(exc: BaseException) -> tuple[str, str]:
    name = type(exc).__name__
    msg = str(exc) or name
    revoked_names = {
        "AuthKeyUnregisteredError",
        "SessionRevokedError",
        "SessionExpiredError",
        "AuthKeyInvalidError",
        "UserDeactivatedError",
        "UserDeactivatedBanError",
        "UnauthorizedError",
    }
    if name in revoked_names or "not authorized" in msg.lower() or "revoked" in msg.lower() or "unregistered" in msg.lower():
        return "SESSION_LOGGED_OUT", f"Sesi TG_SESSION_STRING sudah ter-logout atau kadaluarsa ({name})."
    return "MTPROTO_ERROR", f"{name}: {msg[:240]}"


async def publish_pending(payload_path: Path) -> None:
    if not payload_path.exists():
        print("[PremiumPublisher] No pending channel post found — nothing to publish.")
        return

    try:
        data = json.loads(payload_path.read_text(encoding="utf-8"))
        targets = [str(t).strip() for t in (data.get("targets") or []) if str(t).strip()]
        html_body = str(data.get("html") or "").strip()
        fallback_html = str(data.get("channel_fallback_html") or strip_tg_emoji_tags(html_body)).strip()
        dashboard_url = str(data.get("dashboard_url") or "https://enginebola.web.id").strip()
        expected_owner_id = str(data.get("expected_owner_id") or "").strip() or None

        if not targets or not html_body:
            print("[PremiumPublisher] Empty targets or HTML body — skipping.")
            return

        api_id_raw = os.environ.get("TG_API_ID", "").strip()
        api_hash = os.environ.get("TG_API_HASH", "").strip()
        session_str = os.environ.get("TG_SESSION_STRING", "").strip()

        if not (api_id_raw.isdigit() and api_hash and session_str):
            execute_bot_api_failsafe(
                targets, fallback_html, dashboard_url, expected_owner_id,
                "SESSION_LOGGED_OUT",
                "Secret TG_API_ID / TG_API_HASH / TG_SESSION_STRING kosong atau format tidak valid.",
            )
            return

        try:
            from telethon import TelegramClient
            from telethon.sessions import StringSession
        except Exception as imp_err:
            execute_bot_api_failsafe(
                targets, fallback_html, dashboard_url, expected_owner_id,
                "TELETHON_UNAVAILABLE",
                f"Telethon tidak tersedia ({imp_err}).",
            )
            return

        footer = f'\n\n🔗 <a href="{dashboard_url}"><b>Buka VIP Dashboard · Engine Bola</b></a>'
        full_html = html_body + footer
        chunks = chunk_html_for_telegram(full_html, max_utf16=3900)

        published_targets: set[str] = set()
        client = TelegramClient(StringSession(session_str), int(api_id_raw), api_hash)
        try:
            await client.connect()
            if not await client.is_user_authorized():
                execute_bot_api_failsafe(
                    targets, fallback_html, dashboard_url, expected_owner_id,
                    "SESSION_LOGGED_OUT",
                    "Sesi Telegram (TG_SESSION_STRING) sudah di-logout / tidak terotorisasi.",
                )
                return

            me = await client.get_me()
            actual_id = str(getattr(me, "id", "") or "").strip()
            is_prem = bool(getattr(me, "premium", False))
            print(f"[PremiumPublisher] Connected as id={actual_id} | telegram_premium={is_prem} | expected_owner_id={expected_owner_id or 'any'}")

            # LAYER 1 FAILSAFE: Owner-Override / Takeover Lock
            if expected_owner_id and actual_id and actual_id != expected_owner_id:
                execute_bot_api_failsafe(
                    targets, fallback_html, dashboard_url, expected_owner_id,
                    "OWNER_OVERRIDE_MISMATCH",
                    f"Sesi TG_SESSION_STRING milik akun lama (ID {actual_id}), tidak cocok dengan Owner aktif (ID {expected_owner_id}). Posting dari sesi lama diblokir otomatis.",
                )
                return

            # LAYER 2 FAILSAFE: Telegram Premium expired -> fall back to crisp Unicode flags (🟠🇪🇺)
            if not is_prem:
                execute_bot_api_failsafe(
                    targets, fallback_html, dashboard_url, expected_owner_id,
                    "PREMIUM_EXPIRED",
                    f"Langganan Telegram Premium pada akun Owner (ID {actual_id}) sedang tidak aktif, sehingga custom logo klub tidak bisa dirender di channel.",
                )
                return

            for target in targets:
                peer: Any = int(target) if target.lstrip("-").isdigit() else target
                entity = await client.get_input_entity(peer)
                for idx, html_chunk in enumerate(chunks):
                    text, raw_ents = parse_telegram_html(html_chunk)
                    tl_ents = build_telethon_entities(raw_ents)
                    custom_cnt = sum(1 for e in raw_ents if e["tag"] == "tg-emoji")
                    sent = await client.send_message(
                        entity,
                        text,
                        formatting_entities=tl_ents,
                        link_preview=False,
                    )
                    print(
                        f"[PremiumPublisher] Published chunk {idx + 1}/{len(chunks)} to {target} "
                        f"(msg_id={sent.id}, utf16_len={utf16_len(text)}, custom_emojis={custom_cnt})"
                    )
                    if idx < len(chunks) - 1:
                        await asyncio.sleep(1.5)
                published_targets.add(target)

        except Exception as exc:
            remaining = [t for t in targets if t not in published_targets]
            if remaining:
                code, detail = classify_mtproto_error(exc)
                ok = execute_bot_api_failsafe(
                    remaining, fallback_html, dashboard_url, expected_owner_id,
                    code, detail,
                )
                if not ok:
                    raise
        finally:
            try:
                await client.disconnect()
            except Exception:
                pass
    finally:
        # Always clean up ephemeral payload so stale posts are never left behind or re-sent
        try:
            if payload_path.exists():
                payload_path.unlink()
        except OSError:
            pass


def main() -> None:
    if "--self-test" in sys.argv:
        sample = (
            '<tg-emoji emoji-id="520001">⚽</tg-emoji> <b>ENGINE BOLA</b>\n'
            '<blockquote>1. <tg-emoji emoji-id="520002">🏴󠁧󠁢󠁥󠁮󠁧󠁿</tg-emoji> Crystal Palace vs '
            '<tg-emoji emoji-id="520003">🇪🇸</tg-emoji> Real Sociedad\n'
            '<i>Europa League</i> · <code>1.85</code></blockquote>\n'
            '<a href="https://enginebola.web.id"><b>Buka VIP Dashboard</b></a>'
        )
        text, ents = parse_telegram_html(sample)
        u16 = text.encode("utf-16-le")
        for e in ents:
            slice_txt = u16[e["offset"] * 2 : (e["offset"] + e["length"]) * 2].decode("utf-16-le")
            assert slice_txt, f"Empty entity slice for {e}"
            if e["tag"] == "tg-emoji":
                assert slice_txt in ("⚽", "🏴󠁧󠁢󠁥󠁮󠁧󠁿", "🇪🇸"), f"Bad custom emoji slice: {slice_txt!r}"
        stripped = strip_tg_emoji_tags(sample)
        assert "<tg-emoji" not in stripped and "🏴󠁧󠁢󠁥󠁮󠁧󠁿" in stripped
        class AuthKeyUnregisteredError(Exception):
            pass
        c_code, _ = classify_mtproto_error(AuthKeyUnregisteredError("key unregistered"))
        assert c_code == "SESSION_LOGGED_OUT", f"Unexpected code: {c_code}"
        print(f"[SelfTest OK] text_len={len(text)} utf16={utf16_len(text)} entities={len(ents)} failsafe_classifier=OK")
        return

    repo_root = Path(__file__).resolve().parent.parent
    payload_path = repo_root / "data" / "pending_channel_post.json"
    asyncio.run(publish_pending(payload_path))


if __name__ == "__main__":
    main()
